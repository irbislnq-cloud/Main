enum class ReaderFontStyle(val labelRu: String) {
    SANS_CLEAN("Гротеск (UI)"),
    LITERATA_SERIF("Книжная (Literata)"),
    PLAYFAIR_LITERARY("Классика (Playfair)"),
    JETBRAINS_MONO("Терминал (Mono)");

    fun fontFamily(): FontFamily = when (this) {
        SANS_CLEAN -> BodyFontFamily
        LITERATA_SERIF -> LiterataFontFamily
        PLAYFAIR_LITERARY -> DisplayFontFamily
        JETBRAINS_MONO -> MonoFontFamily
    }

    companion object {
        fun fromString(raw: String?): ReaderFontStyle =
            entries.firstOrNull { it.name == raw } ?: SANS_CLEAN
    }
}

